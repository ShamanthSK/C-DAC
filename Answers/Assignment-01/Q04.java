// Assignment 01 - Question 04: Temperature Conversion
public class Q04 {
    public static void main(String[] args) {
        double celsius = 37.0;

        double fahrenheit = (celsius * 9.0 / 5.0) + 32.0;

        System.out.println("Temperature in Celsius: " + celsius + " deg C");
        System.out.println("Temperature in Fahrenheit: " + fahrenheit + " deg F");
    }
}