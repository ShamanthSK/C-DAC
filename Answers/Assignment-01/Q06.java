// Assignment 01 - Question 06: Even or Odd
public class Q06 {
    public static void main(String[] args) {
        int number = 15;

        System.out.println("Given Number: " + number);
        if (number % 2 == 0) {
            System.out.println(number + " is an Even number.");
        } else {
            System.out.println(number + " is an Odd number.");
        }
    }
}